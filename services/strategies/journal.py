"""The thesis journal: one JSON file per thesis on disk, atomic writes.

Layout, under PATHIEL_STATE_DIR:

    strategies/<desk_id>/theses/<thesis_id>.json

`PATHIEL_STATE_DIR` is resolved at CALL time (not frozen at import), the same
discipline pathiel.agents.capital_flows uses — so a test can point it at a
tmp dir via monkeypatch/fixture without needing to reload this module.

save_thesis() is an upsert (same id -> same file, overwritten atomically via
pathiel.agents.atomic_io.write_json_atomic), which is also how the grader
attaches a Grade to a thesis after it expires: load, set .grade, save_thesis
again.
"""
from __future__ import annotations

import os
from typing import List, Optional

from contracts.strategies.models import Author, Thesis
from pathiel.agents.atomic_io import write_json_atomic

_FALLBACK_STATE_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), ".state")


def _state_dir() -> str:
    return os.environ.get("PATHIEL_STATE_DIR") or _FALLBACK_STATE_DIR


def strategies_dir() -> str:
    return os.path.join(_state_dir(), "strategies")


def theses_dir(desk_id: str) -> str:
    return os.path.join(strategies_dir(), desk_id, "theses")


def thesis_path(desk_id: str, thesis_id: str) -> str:
    # thesis ids are generated by this service (pipeline/facade), never taken
    # verbatim from an HTTP path segment, so no extra sanitizing here.
    return os.path.join(theses_dir(desk_id), f"{thesis_id}.json")


def save_thesis(thesis: Thesis) -> None:
    """Create or overwrite a thesis by (desk_id, id). Atomic: a reader never
    sees a half-written file."""
    path = thesis_path(thesis.desk_id, thesis.id)
    write_json_atomic(path, thesis.model_dump(mode="json"))


def get_thesis(desk_id: str, thesis_id: str) -> Optional[Thesis]:
    path = thesis_path(desk_id, thesis_id)
    if not os.path.exists(path):
        return None
    import json
    with open(path) as fh:
        return Thesis.model_validate(json.load(fh))


def list_theses(desk_id: str, *, author: Optional[Author] = None,
                limit: Optional[int] = None) -> List[Thesis]:
    """Every thesis for this desk, newest first (by created_at). Missing
    directory = no theses yet, not an error."""
    d = theses_dir(desk_id)
    if not os.path.isdir(d):
        return []
    import json
    out: List[Thesis] = []
    for name in os.listdir(d):
        if not name.endswith(".json"):
            continue
        try:
            with open(os.path.join(d, name)) as fh:
                out.append(Thesis.model_validate(json.load(fh)))
        except Exception:  # noqa: BLE001 - one corrupt row shouldn't sink the whole journal
            continue
    if author is not None:
        out = [t for t in out if t.author == author]
    out.sort(key=lambda t: t.created_at, reverse=True)
    return out[:limit] if limit is not None else out


def latest_thesis(desk_id: str, *, author: Optional[Author] = None) -> Optional[Thesis]:
    rows = list_theses(desk_id, author=author, limit=1)
    return rows[0] if rows else None


def all_desk_ids() -> List[str]:
    """Every desk id that has a theses/ directory on disk, regardless of
    whether it's still in the registry — used by the grader so an expired
    thesis never goes unglued just because a desk was retired."""
    base = strategies_dir()
    if not os.path.isdir(base):
        return []
    return sorted(name for name in os.listdir(base)
                 if os.path.isdir(os.path.join(base, name, "theses")))
