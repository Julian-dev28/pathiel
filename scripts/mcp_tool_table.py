#!/usr/bin/env python3
"""Regenerate docs/overhaul/MCP.md from the MCP server's own TOOLS and ALIASES.

    .venv/bin/python scripts/mcp_tool_table.py          # rewrite the doc
    .venv/bin/python scripts/mcp_tool_table.py --check  # exit 1 if it is stale

Deterministic: same server, same table. tests/test_mcp_shoreup.py runs
--check's logic, so a tool added without a category here fails the gate
instead of silently landing in the wrong section.
"""
from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parent.parent
SERVER = ROOT / "scripts" / "pathiel-mcp-server.py"
DOC = ROOT / "docs" / "overhaul" / "MCP.md"

SECTIONS: Dict[str, List[str]] = {
    "Start here: desks, account, risk": [
        "desk_list", "desk_brief", "desk_refresh", "desk_submit_call", "desk_track_record",
        "account_overview", "accounts", "risk_limits", "risk_size_trade",
    ],
    "Agent loop and live-money actions": [
        "scan", "research", "submit_verdict", "execute", "close_position", "set_leverage",
        "cancel_order", "state", "config",
    ],
    "Wallet / dashboard (read-only)": ["connected_wallets", "wallet_account"],
    "Leaderboard / discovery": [
        "leaderboard_get_markets", "leaderboard_get_top_traders", "leaderboard_get_trader_positions",
        "discovery_get_top_traders", "discovery_get_trader_state",
    ],
    "Market data": [
        "get_price", "get_all_mids", "get_candles", "get_price_history", "get_24h_stats",
        "get_l2_book", "get_price_impact", "get_asset_context", "get_assets", "get_coin_info",
        "get_max_leverage", "get_liquidation_price", "get_funding_rate", "get_funding_history",
        "get_predicted_funding", "get_open_interest", "get_spot_markets", "get_user_defined_types",
        "market_get_asset_data", "market_get_funding_regime", "market_list_instruments",
        "get_server_time", "get_network_stats", "get_validator_info", "get_vault_details",
    ],
    "Account / orders / history": [
        "get_account_summary", "get_user_state", "get_asset_positions", "get_portfolio_pnl",
        "get_portfolio_status", "get_risk_metrics", "get_max_trade_size", "get_open_orders",
        "get_order_by_oid", "query_order_by_cloid", "get_historical_orders",
        "get_user_orders_history", "get_trade_history", "get_user_fills_by_time",
        "get_historical_funding", "get_spot_balances", "get_user_fees", "get_referral",
        "get_deposits", "get_withdrawals", "get_transfers", "get_withdrawal_status",
        "get_staking_info", "get_user_twist", "get_rewards", "get_user_roles",
        "get_trading_permissions", "get_api_rate_limits",
    ],
}


def _load_server():
    spec = importlib.util.spec_from_file_location("pathiel_mcp_server_table", SERVER)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _safety(name: str, m) -> str:
    if name in m.LIVE_MONEY_TOOLS:
        return "LIVE MONEY"
    if name in m.LIVE_CONFIG_TOOLS:
        return "writes live config"
    if name in m.LOCAL_WRITE_TOOLS:
        return "writes journal"
    return "read-only"


def render(m=None) -> str:
    m = m or _load_server()
    tools = {t["name"]: t for t in m.TOOLS}
    placed = [n for names in SECTIONS.values() for n in names]
    unplaced = sorted(set(tools) - set(placed))
    if unplaced:
        raise SystemExit(f"tools with no section in scripts/mcp_tool_table.py: {unplaced}")
    aliases: Dict[str, List[str]] = {}
    for alias, canonical in m.ALIASES.items():
        aliases.setdefault(canonical, []).append(alias)
    out = [
        "# MCP tool table",
        "",
        f"`scripts/pathiel-mcp-server.py`: {len(tools)} tools over stdio. Generated by "
        "`scripts/mcp_tool_table.py` from the server's TOOLS and ALIASES; do not edit by hand.",
        "",
        "LIVE-MONEY tools (never call outside a mocked test): "
        + ", ".join(f"**{n}**" for n in sorted(m.LIVE_MONEY_TOOLS)) + ".",
        "",
        "Every tool carries MCP annotations (readOnlyHint / destructiveHint). Live smoke over "
        "the real transport: `.venv/bin/python scripts/mcp_smoke.py`.",
    ]
    for title, names in SECTIONS.items():
        out += ["", f"## {title}", "", "| tool | safety | also answers (hidden aliases) | description |",
                "|---|---|---|---|"]
        for n in names:
            if n not in tools:
                continue
            desc = " ".join(tools[n]["description"].split()).replace("|", "\\|")
            al = ", ".join(f"`{a}`" for a in sorted(aliases.get(n, [])))
            out.append(f"| `{n}` | {_safety(n, m)} | {al} | {desc} |")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the doc is stale")
    a = ap.parse_args()
    text = render()
    if a.check:
        current = DOC.read_text() if DOC.exists() else ""
        if current != text:
            print(f"{DOC} is stale: run scripts/mcp_tool_table.py", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(text)
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
